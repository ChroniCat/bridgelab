import assert from 'node:assert/strict';
import {createRun,observeRun,recordIncident,completeRun,bundleFor} from '../field/storage.js';

const site={id:'trial',name:'Walk',revision:4,sections:[{id:'A',name:'First bay'},{id:'B',name:'Second bay'}]};
const run=createRun(site,{source:'synthetic',handoffs:[]});
observeRun(run,{t:0,sectionId:'A',valid:true,checkPx:.5});
observeRun(run,{t:200,sectionId:'A',valid:true,checkPx:.9});
observeRun(run,{t:400,reason:'occlusion'});
observeRun(run,{t:5200,sectionId:'A',valid:true,checkPx:.3});
recordIncident(run,{t:5200,sectionId:'A',kind:'metric',dxMm:-2,dyMm:3});
run.handoffs.push({t:5200,from:'A',to:'A',reacquiredAfterMs:4800});
completeRun(run,5400);
assert.equal(run.validMs,200);
assert.equal(run.unattributedMs,5200);
assert.deepEqual([run.validFrames,run.processedFrames,run.unlocatedFrames],[3,4,1]);
assert.equal(run.coverage.A.visits,2);
assert.equal(run.coverage.A.maxCheckPx,.9);
assert.equal(run.coverage.B.frames,0);
assert.equal(run.coverage.B.validMs,0);
assert.equal(run.rejections.occlusion,1);
observeRun(run,{t:5500,sectionId:'B',valid:true});
assert.equal(run.coverage.B.frames,0);
assert.throws(()=>recordIncident(run,{t:5500,sectionId:'B'}),e=>e.code==='invalid-event');
const label={runId:run.id,index:0,t:5200,predicted:'A',actual:'B',updatedAt:123};
const file=bundleFor({...run,reviewLabels:[label]},site);
assert.equal(file.sites[0].revision,4);
assert.equal(file.runs[0].handoffs[0].to,'A');
assert.equal(file.runs[0].incidents[0].dxMm,-2);
assert.equal(file.runs[0].reviewLabels,undefined);
assert.deepEqual(file.reviews,[label]);
assert.throws(()=>bundleFor(run,{...site,revision:5}),e=>e.code==='invalid-bundle');
console.log('Passed: immutable run geometry revision, independent handoff labels, outage-inclusive coverage and signed incident export.');
